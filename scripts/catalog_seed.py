"""Build app/src/main/assets/catalog-seed.json from a device's diagnostics.

A first visit to a title is the one case the on-disk cache cannot help with: nothing has been
learned yet, so every provider is asked over the network and the viewer waits 2-14 seconds per
provider. Shipping the answers for settled titles removes that for anything covered.

Only FINISHED and CANCELLED titles are taken. A finished series has the episode count it will
always have; anything still airing would be wrong within a week and stay wrong until the app
updated, which is worse than asking.

Episode counts only. This once also wrote a `titles` map of provider slugs, which would have been
the more valuable half — a slug is the expensive part of a lookup, and it never goes stale — but it
shipped empty for its whole life and always would have: DiagnosticRedactor blanks any attribute
named `slug`, and it does so on the way into events-main.jsonl, so the input read below has never
contained one. That boundary exists so a viewer's slugs stay on their device, so the map was
dropped rather than the redaction loosened. Counts name nothing and are safe to ship.

Usage:
    adb exec-out run-as com.miruronative.debug cat files/diagnostics/events-main.jsonl > events.jsonl
    python scripts/catalog_seed.py events.jsonl [more.jsonl ...]
"""
from __future__ import annotations

import json
import pathlib
import sys
from collections import defaultdict

SEED = pathlib.Path(__file__).resolve().parent.parent / "app/src/main/assets/catalog-seed.json"
SETTLED = {"FINISHED", "CANCELLED"}


def rows(paths: list[str]):
    for path in paths:
        with open(path, encoding="utf-8", errors="replace") as handle:
            for line in handle:
                line = line.strip()
                if line.startswith("{"):
                    try:
                        yield json.loads(line)
                    except json.JSONDecodeError:
                        continue


def main(paths: list[str]) -> int:
    learned: dict[str, dict[str, dict[str, int]]] = defaultdict(dict)
    skipped_airing = 0

    for row in rows(paths):
        attrs = row.get("attributes") or {}
        if row.get("name") == "catalog.availability.learned":
            if attrs.get("status") not in SETTLED:
                skipped_airing += 1
                continue
            sub, dub = int(attrs.get("sub", 0)), int(attrs.get("dub", 0))
            if sub <= 0 and dub <= 0:
                continue
            entry: dict[str, int] = {}
            if sub > 0:
                entry["s"] = sub
            if dub > 0:
                entry["d"] = dub
            learned[str(attrs["anilistId"])][attrs["provider"]] = entry

    existing = json.loads(SEED.read_text(encoding="utf-8")) if SEED.exists() else {}
    seed = {
        "_comment": existing.get(
            "_comment",
            "Answers for settled titles, so a first visit does not have to ask the network. "
            "availability: anilistId -> provider -> {s: highest sub episode, d: highest dub}. "
            "Generated by scripts/catalog_seed.py; a miss falls through to the live lookup.",
        ),
        "version": 1,
        "generated": existing.get("generated"),
        "availability": {**existing.get("availability", {}), **learned},
    }
    from datetime import date

    seed["generated"] = date.today().isoformat()
    SEED.write_text(json.dumps(seed, indent=1, sort_keys=True) + "\n", encoding="utf-8")

    entries = sum(len(v) for v in seed["availability"].values())
    print(f"titles {len(seed['availability'])}, provider answers {entries}")
    print(f"skipped {skipped_airing} still-airing answers")
    print(f"{SEED} is {SEED.stat().st_size / 1024:.1f} KB")
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        raise SystemExit(2)
    raise SystemExit(main(sys.argv[1:]))
