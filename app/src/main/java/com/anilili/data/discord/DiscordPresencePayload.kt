package com.anilili.data.discord

import org.json.JSONArray
import org.json.JSONObject

/**
 * What the viewer is watching, in the terms a presence card needs. Position and duration are the
 * player's own clock; everything else comes off the episode being played.
 */
data class DiscordWatching(
    val seriesTitle: String,
    val episodeNumber: String?,
    val episodeTitle: String?,
    val totalEpisodes: Int?,
    val artworkUrl: String?,
    val anilistId: Int,
    val positionMs: Long,
    val durationMs: Long,
    val paused: Boolean,
) {
    /**
     * The identity of the *thing being watched*, with the clock deliberately left out. Two updates
     * that differ only in position describe the same card, and Discord keeps the progress bar
     * moving on its own once it has been given a start — so republishing on every tick would spend
     * the gateway's presence rate limit to change nothing.
     *
     * The episode title is part of it because it is the card's second line and can arrive late:
     * the episode list lands as a numbered skeleton first and gains its titles afterwards, so a
     * card published in between would otherwise keep the bare number for the whole episode.
     */
    val cardIdentity: String
        get() = "$anilistId/$seriesTitle/$episodeNumber/$episodeTitle/$paused"
}

/**
 * Discord activity types. Only [WATCHING] is used; the rest are here because the wire value is a
 * bare integer and a named constant is the difference between reading this and looking it up.
 */
internal object DiscordActivityType {
    const val PLAYING = 0
    const val LISTENING = 2
    const val WATCHING = 3
}

/**
 * Which activity field the member list and the status line read after "Watching": the app's name
 * (Discord's default, "Watching Anilili"), the `state` line, or the `details` line.
 */
internal object DiscordStatusDisplayType {
    const val NAME = 0
    const val STATE = 1
    const val DETAILS = 2
}

/** Discord truncates past these and rejects a `details`/`state` shorter than two characters. */
private const val MAX_TEXT = 128
private const val MAX_BUTTON_LABEL = 32
private const val MAX_BUTTON_URL = 512

/** The card's one button, which opens the project's Discord server (Settings > About's link). */
internal const val WATCH_BUTTON_LABEL = "Get Anilili"
internal const val WATCH_BUTTON_URL = "https://discord.gg/Anilili"

/**
 * The keys the small-badge art was uploaded under in the developer portal.
 *
 * These are names to *look assets up by*, not values to send: an activity's assets take an asset id
 * or an `mp:` path, so the id is resolved through [DiscordAssets.applicationAssetId] and that is
 * what reaches the wire.
 *
 * `paused` is generated by `scripts/discord_presence_assets.py`; `icon` is the app's own mark,
 * uploaded from `anilili-logo.png`.
 */
internal const val PAUSED_ASSET_KEY = "paused"
internal const val APP_ICON_ASSET_KEY = "icon"

/**
 * Builds the op 3 payload.
 *
 * Pure, and takes its clock as an argument, so the shape of a card can be asserted in a unit test
 * rather than read off a phone.
 *
 * [largeImage] is passed through already resolved — either an `mp:external/…` path from
 * [DiscordAssets], or a bare application asset key — because turning a cover URL into one of those
 * is a network call and this is not.
 */
internal fun buildPresencePayload(
    watching: DiscordWatching,
    appName: String,
    largeImage: String?,
    smallImage: String? = null,
    status: String = "online",
    nowMs: Long,
): JSONObject {
    val activity = JSONObject()
        .put("name", appName.take(MAX_TEXT))
        .put("type", DiscordActivityType.WATCHING)
        // A number rather than a string. Snowflakes are usually quoted in Discord's REST
        // payloads, but op 3 is the Social SDK's own path and the shape that is known to be
        // accepted there is the numeric one; an int64 survives it exactly.
        .put("application_id", DiscordAuthManager.APPLICATION_ID.toLong())
        .put("platform", "android")

    presenceText(watching.seriesTitle)?.let { series ->
        activity.put("details", series)
        // The member list reads "Watching <series>" rather than "Watching Anilili", as the desktop
        // app's card does. Only with a series line to point at; without one the name stays.
        activity.put("status_display_type", DiscordStatusDisplayType.DETAILS)
    }
    presenceText(stateLine(watching))?.let { activity.put("state", it) }

    // A paused episode gets no timestamps at all. Discord has no way to hold a progress bar
    // still, so the choice is between a bar that keeps advancing while nothing plays and no bar
    // at all — and a card that lies about where a viewer is is worse than one that stays quiet.
    if (!watching.paused) {
        timestamps(watching, nowMs)?.let { activity.put("timestamps", it) }
    }

    val assets = JSONObject()
    largeImage?.takeIf { it.isNotBlank() }?.let { assets.put("large_image", it) }
    // The badge carries the app's mark while playing and swaps to the pause glyph when stopped, so
    // the slot says who is playing this rather than sitting empty for all but one state. The cover
    // is the title's, and a card in a member list is otherwise only identifiable from its header.
    //
    // No badge at all beats a broken one: with an unresolvable image Discord still honours
    // `small_text`, so the card renders a "?" that hovers as "Paused" and reads as a bug.
    if (smallImage != null) {
        assets.put("small_image", smallImage)
        // Only when paused. Naming the app here would repeat the "Watching Anilili" header for the
        // sake of filling a tooltip, which is exactly what the cover tooltip already avoids.
        if (watching.paused) assets.put("small_text", "Paused")
    }
    if (assets.length() > 0) activity.put("assets", assets)

    // The button sends whoever sees the card to the project rather than to the series: there are no
    // per-title pages to link, and a viewer who wants the series can find it once they have the app.
    activity.put("buttons", JSONArray().put(WATCH_BUTTON_LABEL.take(MAX_BUTTON_LABEL)))
    activity.put(
        "metadata",
        JSONObject().put("button_urls", JSONArray().put(WATCH_BUTTON_URL.take(MAX_BUTTON_URL))),
    )

    return sessionPresence(status, nowMs).put("activities", JSONArray().put(activity))
}

/** The payload that takes the card down while leaving the connection up. */
internal fun clearedPresencePayload(status: String = "online", nowMs: Long = 0L): JSONObject =
    sessionPresence(status, nowMs).put("activities", JSONArray())

/**
 * The session-level half of every presence this app sends.
 *
 * For the default "online" status this is byte for byte what 0.1.79 sent — `afk: false`,
 * `since: null` — and that is deliberate. 0.1.80 changed it to `afk: true` and `since: 0` (and put
 * it into IDENTIFY), hoping an AFK session would stop holding back the viewer's Discord phone
 * pushes; no card was published by 0.1.80 anywhere, and none of the three changes had ever been
 * tried against a real account. IDENTIFY is presence-free again (see DiscordGateway.sendIdentify)
 * and these two fields are back to the values that are known to work.
 *
 * The push-notification report stands and `afk: true` may still be its answer, but it has to be
 * proven on a signed-in account — card showing *and* pushes arriving mid-episode — before it
 * ships again.
 *
 * `since` is when the client went idle, which Discord needs for the idle status only.
 */
internal fun sessionPresence(status: String, nowMs: Long): JSONObject = JSONObject()
    .put("status", status)
    .put("afk", false)
    .put("since", if (status == "idle") nowMs else JSONObject.NULL)

/**
 * Which episode, and how many there are when that is known. Null for a film, which has no number.
 */
internal fun episodeLabel(watching: DiscordWatching): String? {
    val number = watching.episodeNumber?.takeIf { it.isNotBlank() } ?: return null
    val total = watching.totalEpisodes?.takeIf { it > 0 }
    return if (total != null) "Ep: $number/$total" else "Ep: $number"
}

private fun episodeTitle(watching: DiscordWatching): String? =
    watching.episodeTitle?.trim()?.takeIf { it.isNotEmpty() }

/**
 * The second line of the card, "Ep: 10/200 - Its Title": [episodeLabel], then the episode's own
 * title when the provider or catalogue gave one. A film has no number, so its title is all there
 * is to say. Discord ellipsises `state` on one line, so a long title is cut, not wrapped.
 *
 * The desktop app's card (`discord.rs`) says the same; keep the two in step.
 */
internal fun stateLine(watching: DiscordWatching): String? {
    val label = episodeLabel(watching)
    val title = episodeTitle(watching)
    return when {
        label != null && title != null -> "$label - $title"
        else -> label ?: title
    }
}

/**
 * Start and end as epoch millis, which is what makes Discord draw the elapsed/remaining bar.
 *
 * Start is back-dated by however far into the episode the viewer already is, so the bar lands in
 * the right place immediately instead of restarting from zero on every episode change.
 */
private fun timestamps(watching: DiscordWatching, nowMs: Long): JSONObject? {
    if (watching.durationMs <= 0) return null
    val position = watching.positionMs.coerceIn(0, watching.durationMs)
    val startedAt = nowMs - position
    return JSONObject()
        .put("start", startedAt)
        .put("end", startedAt + watching.durationMs)
}

/**
 * Discord drops a `details` or `state` under two characters rather than showing it, so a
 * one-character value is the same as none and is reported as none here.
 */
private fun presenceText(value: String?): String? =
    value?.trim()?.takeIf { it.length >= 2 }?.take(MAX_TEXT)
