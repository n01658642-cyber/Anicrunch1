/**
 * Episode stills and titles from TMDB, for the episodes the metadata CDN has no picture of.
 *
 * The CDN tree is a static mirror of this same API and is preferred wherever it has an answer: it
 * is one cache-friendly request and costs no key. It used to be AlokRepo/Konoha, a third-party
 * backfill that had reached 2010 and stopped syncing, and this class existed to paper over how much
 * it was missing. The tree is now generated by `scripts/konoha_build.py` and refreshed daily, so
 * that gap is mostly closed — 20,778 titles, of which 6,113 carry an episode list.
 *
 * What is left for this class is narrower but real: the episode that aired since the last nightly
 * build, the twelve hours jsDelivr may serve a stale tree for, and any title the generator declined
 * to match. It answers for those and nothing else; a title the tree covers never reaches here.
 *
 * The matching below is shared with that generator, which ported it. When the two disagree a viewer
 * gets one show's stills on another show's episodes, so a change here needs the same change there —
 * `scripts/test_konoha_build.py` pins the cases that have gone wrong before.
 *
 * Without a configured token every method answers empty, which leaves the app exactly where it was.
 */
class TmdbClient(
    private val client: OkHttpClient,
    private val json: Json,
    private val cache: AppCache,
    private val readToken: String,
) {
    val isConfigured: Boolean get() = readToken.isNotBlank()

    /**
     * Titles and stills for [media]'s episodes, keyed by AniList episode number, or empty when
     * TMDB has no record this can be matched to with confidence.
     *
     * The answer is cached either way. A miss costs a search plus a season fetch, and a title TMDB
     * genuinely does not have would otherwise pay that on every visit to its page; the same six
     * hours Konoha's episode lists use is short enough that a newly added still is not far away.
     */
    suspend fun episodeMetadata(media: Media, hint: TmdbRef?): List<EpisodeMetadata> {
        if (!isConfigured) return emptyList()
        return withContext(Dispatchers.IO) {
            runCatching {
                cache.getOrFetch(
                    key = "tmdbeps:v2:${media.id}",
                    serializer = ListSerializer(EpisodeMetadata.serializer()),
                    ttlMs = EPISODES_TTL_MS,
                ) { fetchEpisodes(media, hint) }
            }
                .onFailure { DiagnosticsLog.throwable("TMDB episodes failed id=${media.id}", it) }
                .getOrDefault(emptyList())
        }
    }

    /**
     * Wide backdrops of [media]'s show as full-size URLs, pictures without text first and then by
     * TMDB's votes; empty when TMDB has nothing this can be matched to with confidence.
     *
     * Matched exactly as the episode stills are, so a title that gets another show's stills would
     * get its backdrops too — and a fix to the matching fixes both. TMDB keeps backdrops per series,
     * not per season, so a sequel's page offers the whole show's.
     */
    suspend fun backdrops(media: Media, hint: TmdbRef?): List<String> {
        if (!isConfigured) return emptyList()
        return withContext(Dispatchers.IO) {
            runCatching {
                cache.getOrFetch(
                    key = "tmdbbackdrops:v1:${media.id}",
                    serializer = ListSerializer(String.serializer()),
                    ttlMs = BACKDROPS_TTL_MS,
                ) { fetchBackdrops(media, hint) }
            }
                .onFailure { DiagnosticsLog.throwable("TMDB backdrops failed id=${media.id}", it) }
                .getOrDefault(emptyList())
        }
    }

    private suspend fun fetchBackdrops(media: Media, hint: TmdbRef?): List<String> {
        val path = resolveSeries(media, hint)?.let { "/tv/${it.id}/images" }
            ?: resolveMovie(media)?.let { "/movie/${it.id}/images" }
            ?: return emptyList()
        // `null` is TMDB's spelling of "no language": the text-free pictures.
        val images = get("$path?include_image_language=null,en,ja", TmdbImages.serializer())
            ?.backdrops.orEmpty()
        return images
            .filter { it.file_path.isNotBlank() }
            .sortedWith(compareBy<TmdbImage> { if (it.iso_639_1 == null) 0 else 1 }.thenByDescending { it.vote_average })
            .take(MAX_BACKDROPS)
            .map { TMDB_BACKDROP_BASE + it.file_path }
    }

    /** A film entry's own TMDB record, found the way [movieRun] finds a run of them. */
    private suspend fun resolveMovie(media: Media): TmdbMovie? {
        if (media.format !in MOVIE_RUN_FORMATS) return null
        val found = LinkedHashMap<Int, TmdbMovie>()
        for (query in movieSearchQueries(media)) {
            get("/search/movie?query=" + URLEncoder.encode(query, "UTF-8"), TmdbMovieSearchResponse.serializer())
                ?.results
                .orEmpty()
                .forEach { found.putIfAbsent(it.id, it) }
        }
        return pickMovieRun(media.copy(episodes = media.episodes ?: 1), found.values.toList())?.firstOrNull()
    }

    private suspend fun fetchEpisodes(media: Media, hint: TmdbRef?): List<EpisodeMetadata> {
        val series = resolveSeries(media, hint)
            ?: return parentSpecialsRun(media).ifEmpty { movieRun(media) }
        val wantedEpisodes = media.episodes
        val wantedYear = media.seasonYear ?: media.startDate?.year
        // The day the season began, which is the only thing that separates two cours of one series
        // broadcast in the same year — see [nearestOpener].
        val wantedStart = isoAirDate(media.startDate)

        // An entry AniList keeps as one long run that TMDB splits into broadcast seasons is the
        // whole series, and no single season or group run can stand for it — see [wholeSeriesSeasons].
        val wholeRun = wholeSeriesSeasons(series.seasons, wantedEpisodes)
        if (wholeRun.isNotEmpty()) {
            val episodes = wholeRun.chunked(MAX_APPENDED_SEASONS).flatMap { chunk ->
                val appended = chunk.joinToString(",") { "season/${it.season_number}" }
                val payload = get("/tv/${series.id}?append_to_response=$appended", JsonObject.serializer())
                chunk.flatMap { summary ->
                    payload?.get("season/${summary.season_number}")
                        ?.let { json.decodeFromJsonElement(TmdbSeason.serializer(), it).episodes }
                        .orEmpty()
                }
            }
            if (episodes.size == wantedEpisodes) {
                DiagnosticsLog.event(
                    "TMDB matched anilist=${media.id} tmdb=${series.id} seasons=${wholeRun.size} " +
                        "episodes=${episodes.size} (whole series)",
                )
                return episodes.toMetadata()
            }
        }

        pickSeason(series.seasons, wantedEpisodes, wantedYear, wantedStart)?.let { summary ->
            val episodes = get("/tv/${series.id}/season/${summary.season_number}", TmdbSeason.serializer())
                ?.episodes
                .orEmpty()
            if (episodes.isNotEmpty()) {
                DiagnosticsLog.event(
                    "TMDB matched anilist=${media.id} tmdb=${series.id} season=${summary.season_number} " +
                        "episodes=${episodes.size}",
                )
                return episodes.toMetadata()
            }
        }

        // No season lines up, which is what a series TMDB keeps as one long run looks like: it
        // holds Dandadan's two AniList seasons as a single season of 24 and Re:Zero's four as one
        // of 85. TMDB's own answer to that is an episode group, and the "Seasons" kind splits the
        // run back into the seasons the rest of the world numbers from — carrying the stills with
        // it, so the split costs one request rather than a fetch per season.
        val groups = get("/tv/${series.id}/episode_groups", TmdbEpisodeGroupList.serializer())
            ?.results
            .orEmpty()
            .filter { it.type in SEASONS_GROUP_TYPES && it.group_count > 1 }
            .sortedWith(
                compareBy<TmdbEpisodeGroupSummary> { SEASONS_GROUP_TYPES.indexOf(it.type) }
                    .thenByDescending { it.episode_count },
            )
            .take(MAX_GROUPS_TRIED)
        for (group in groups) {
            val detail = get("/tv/episode_group/${group.id}", TmdbEpisodeGroupDetail.serializer()) ?: continue
            val matched = pickGroup(detail.groups, wantedEpisodes, wantedYear, wantedStart) ?: continue
            DiagnosticsLog.event(
                "TMDB matched anilist=${media.id} tmdb=${series.id} group=${group.id} " +
                    "run=${matched.name} episodes=${matched.episodes.size}",
            )
            return matched.episodes.toMetadata()
        }

        // A one-episode entry matches no numbered season and no group by count, because TMDB does
        // not give a special a season of its own — it files it under season 0 with the date it
        // aired. Attack on Titan's two FINAL CHAPTERS specials are AniList entries of one episode
        // each and TMDB season 0 episodes 36 and 37, and nothing above can see them.
        specialsEpisode(media, series.id, wantedEpisodes)?.let { episode ->
            DiagnosticsLog.event(
                "TMDB matched anilist=${media.id} tmdb=${series.id} special=${episode.air_date}",
            )
            return listOf(episode).toMetadata()
        }

        // Nothing lines up on this series' own terms, so the count match whose year did not fit is
        // taken after all rather than leaving the title with no episode titles at all.
        farYearSeason(series.seasons, wantedEpisodes, wantedYear)?.let { summary ->
            val episodes = get("/tv/${series.id}/season/${summary.season_number}", TmdbSeason.serializer())
                ?.episodes
                .orEmpty()
            if (episodes.isNotEmpty()) {
                DiagnosticsLog.event(
                    "TMDB matched anilist=${media.id} tmdb=${series.id} " +
                        "season=${summary.season_number} episodes=${episodes.size} (year mismatch)",
                )
                return episodes.toMetadata()
            }
        }
        // Last: the entry is not on the series at all because TMDB keeps its episodes as films.
        movieRun(media).takeIf { it.isNotEmpty() }?.let { return it }
        DiagnosticsLog.event("TMDB no season matched anilist=${media.id} tmdb=${series.id}")
        return emptyList()
    }

    /**
     * An OVA or film entry whose episodes TMDB keeps as separate movies rather than as a season.
     *
     * Re:ZERO's two OVAs are AniList 100049 with two episodes, and TMDB 532321 ("Memory Snow") and
     * 566451 ("The Frozen Bond") — released on exactly the AniList entry's start and end dates. No
     * season, group or special holds them, so the page showed two blank cards. Tried only after
     * every series route has failed, and only on the terms [pickMovieRun] sets out.
     */
    private suspend fun movieRun(media: Media): List<EpisodeMetadata> {
        if (media.format !in MOVIE_RUN_FORMATS) return emptyList()
        val wanted = media.episodes ?: return emptyList()
        if (wanted !in 1..MAX_MOVIE_RUN) return emptyList()
        val found = LinkedHashMap<Int, TmdbMovie>()
        for (query in movieSearchQueries(media)) {
            get("/search/movie?query=" + URLEncoder.encode(query, "UTF-8"), TmdbMovieSearchResponse.serializer())
                ?.results
                .orEmpty()
                .forEach { found.putIfAbsent(it.id, it) }
        }
        val run = pickMovieRun(media, found.values.toList()) ?: return emptyList()
        DiagnosticsLog.event(
            "TMDB matched anilist=${media.id} movies=${run.joinToString(",") { it.id.toString() }}",
        )
        return run.mapIndexed { index, movie ->
            TmdbEpisode(
                episode_number = index + 1,
                name = movieEpisodeTitle(media, movie),
                // A film has no still; its backdrop is the same kind of picture, a frame at 16:9.
                still_path = movie.backdrop_path,
                air_date = movie.release_date,
                overview = movie.overview,
                vote_average = movie.vote_average,
            )
        }.toMetadata()
    }

    /**
     * The single episode of a one-episode entry, found by its air date in TMDB's specials season.
     *
     * Only a stated count of exactly one is answered here: for anything longer the season and group
     * matching is the better instrument, and a date on its own would be a guess. The date has to be
     * AniList's own and match a season 0 episode exactly, and exactly one of them — two specials of
     * the same series on the same day cannot be told apart by this.
     */
    private suspend fun specialsEpisode(media: Media, seriesId: Int, wantedEpisodes: Int?): TmdbEpisode? {
        if (wantedEpisodes != 1) return null
        val aired = isoAirDate(media.startDate) ?: return null
        val episodes = get("/tv/$seriesId/season/$SPECIALS_SEASON", TmdbSeason.serializer())
            ?.episodes
            .orEmpty()
            .filter { it.air_date == aired }
        return episodes.singleOrNull()
    }

    /**
     * A side series that TMDB has no show for, found among its AniList parent's specials by name.
     *
     * TMDB files chibi shorts and similar spin-offs as season 0 of the main show, each episode
     * named after the spin-off: Youjo Shenki is "Youjo Shenki: Mini-Episode 00" through 12 under
     * Saga of Tanya the Evil, followed by "Youjo Shenki 2: Mini-Episode 1" through 12. Searching
     * TMDB for the spin-off finds nothing, so without this both entries had no stills at all.
     */
    private suspend fun parentSpecialsRun(media: Media): List<EpisodeMetadata> {
        val parent = media.relations.edges.firstOrNull { it.relationType == "PARENT" }?.node
            ?: return emptyList()
        val series = resolveSeries(parent, hint = null) ?: return emptyList()
        val specials = get("/tv/${series.id}/season/$SPECIALS_SEASON", TmdbSeason.serializer())
            ?.episodes
            .orEmpty()
        val run = specialsRunFor(media, specials)
        if (run.isEmpty()) return emptyList()
        DiagnosticsLog.event(
            "TMDB matched anilist=${media.id} tmdb=${series.id} parent=${parent.id} specials=${run.size}",
        )
        return run.toMetadata()
    }

    /**
     * The TMDB series for [media], checked against the AniList record before it is believed.
     *
     * The bundled map is consulted first because it costs nothing, but it is only a guess and a
     * wrong one is worse than none: it rates AniList 171018 (Dandadan) a HIGH-confidence match for
     * a 2024 Chinese drama, and had that been taken at face value the episode list would have been
     * decorated with that drama's stills. So the map's answer has to survive [titlesMatch] like any
     * other candidate, and a rejected one falls through to a search.
     */
    private suspend fun resolveSeries(media: Media, hint: TmdbRef?): TmdbSeries? {
        if (hint != null && hint.type != "movie") {
            val candidate = get("/tv/${hint.id}", TmdbSeries.serializer())
            if (candidate != null) {
                if (titlesMatch(media, candidate)) return candidate
                DiagnosticsLog.event(
                    "TMDB id-map rejected anilist=${media.id} tmdb=${hint.id} " +
                        "(${candidate.name} does not match ${media.title.preferred})",
                )
            }
        }
        // Both the title as AniList writes it and the title with its season marker removed. TMDB
        // indexes the series, not the season: searching its own name for "Youjo Senki II" returns
        // nothing at all, while "Youjo Senki" finds the show whose second season this is.
        val queries = listOf(media.title.romaji, media.title.english)
            .flatMap { listOf(it?.trim(), seriesSearchQuery(it)) }
            .filterNot { it.isNullOrBlank() }
            .filterNotNull()
            .distinct()
        for (query in queries) {
            val results = get(
                "/search/tv?query=" + URLEncoder.encode(query, "UTF-8"),
                TmdbSearchResponse.serializer(),
            )?.results.orEmpty()
            val match = results.firstOrNull { titlesMatch(media, it) } ?: continue
            return get("/tv/${match.id}", TmdbSeries.serializer())
        }
        return null
    }

    private fun <T> get(path: String, serializer: KSerializer<T>): T? {
        val separator = if ('?' in path) "&" else "?"
        val request = Request.Builder()
            .url("$API_BASE$path${separator}language=en-US")
            .header("Authorization", "Bearer $readToken")
            .header("Accept", "application/json")
            .build()
        return client.newCall(request).execute().use { response ->
            when {
                // 404 is an ordinary answer here: an id-map guess can point at a record that no
                // longer exists, and a series can simply have no episode groups.
                response.code == 404 -> null
                !response.isSuccessful -> error("TMDB HTTP ${response.code} for $path")
                else -> json.decodeFromString(serializer, response.body?.string().orEmpty())
            }
        }
    }

    private companion object {
        const val API_BASE = "https://api.themoviedb.org/3"
        /**
         * The TMDB grouping types that split a run by when it aired, most trusted first: production
         * (6), original air date (1) and TV (7). Which one a series' editors used is arbitrary —
         * Dandadan and Re:Zero carry a production split, while The Apothecary Diaries keeps all 60
         * episodes as one season and splits them only by air date ("Seasons") and TV ("Cours"), so
         * reading production alone left both of its AniList seasons without a single still.
         * Absolute, DVD, digital and story-arc groupings are not the broadcast seasons.
         */
        val SEASONS_GROUP_TYPES = listOf(6, 1, 7)
        /** TMDB's cap on `append_to_response`; Naruto Shippuden's twenty seasons fit in one call. */
        const val MAX_APPENDED_SEASONS = 20
        /** Re:Zero carries eight groupings; trying them all would cost more than the stills are worth. */
        const val MAX_GROUPS_TRIED = 3
        /** The AniList formats whose episodes TMDB may keep as films instead of as a season. */
        val MOVIE_RUN_FORMATS = setOf("MOVIE", "OVA", "ONA", "SPECIAL")
        /** Beyond a handful, a run of films standing in for one entry's episodes is not the pattern. */
        const val MAX_MOVIE_RUN = 6
        /** TMDB files everything that is not a numbered season under season 0. */
        const val SPECIALS_SEASON = 0
        /** Matches the Konoha episode TTL: airing shows gain an episode a week. */
        const val EPISODES_TTL_MS = 6L * 60 * 60 * 1000
        /** Backdrops are added rarely; a week keeps the picker to one TMDB call per title per week. */
        const val BACKDROPS_TTL_MS = 7L * 24 * 60 * 60 * 1000
        /** More than a picker page's worth is scrolling nobody does. */
        const val MAX_BACKDROPS = 12
        /** `w1280` rather than `original`: the background is drawn at half a screen's resolution. */
        const val TMDB_BACKDROP_BASE = "https://image.tmdb.org/t/p/w1280"
    }
}

/** TMDB serves stills as paths; `w500` is wider than any episode row the app draws. */
internal fun tmdbStillUrl(path: String?): String? =
    path?.takeIf { it.isNotBlank() }?.let { "https://image.tmdb.org/t/p/w500$it" }

/**
 * A run of TMDB episodes as the app's own metadata, numbered by position rather than by TMDB's
 * `episode_number`.
 *
 * Position is what survives both shapes. Where TMDB keeps a season of its own the two agree, but
 * inside a merged run the second season's episodes are numbered 13..24 while every other catalogue
 * — AniList, the stream providers, the viewer — calls them 1..12.
 */
internal fun List<TmdbEpisode>.toMetadata(): List<EpisodeMetadata> = mapIndexed { index, episode ->
    EpisodeMetadata(
        number = (index + 1).toDouble(),
        title = episode.name?.takeIf { it.isNotBlank() },
        still = tmdbStillUrl(episode.still_path),
        airDate = episode.air_date?.takeIf { it.isNotBlank() },
        overview = episode.overview?.takeIf { it.isNotBlank() },
        runtime = episode.runtime?.takeIf { it > 0 },
        // TMDB scores an episode nobody has voted on as 0.0, which is not a score of zero but the
        // absence of one, and a row that showed it would be accusing the episode of something.
        rating = episode.vote_average?.takeIf { it > 0.0 },
    )
}

/**
 * Titles reduced to what two catalogues can be expected to agree on.
 *
 * Punctuation, spacing and case never survive the trip between AniList and TMDB — "Re:ZERO
 * -Starting Life in Another World-" against "Re:ZERO -Starting Life in Another World-" is the easy
 * case and "Dandadan" against "Dan Da Dan" is the normal one. Season markers go too: this decides
 * which *series* a title belongs to, and the season is chosen separately by episode count and year.
 */
internal fun normalizeTitle(raw: String?): String =
    seriesSearchQuery(raw).orEmpty().lowercase().filter { it.isLetterOrDigit() }

/**
 * A title as the name of its series rather than of one season: what to ask TMDB's search for.
 *
 * TMDB indexes the show and splits it into seasons underneath, so a season's own name finds
 * nothing — "Youjo Senki II" returns no results where "Youjo Senki" returns the show this is the
 * second season of. Which season then gets used is decided separately, by episode count and year.
 */
internal fun seriesSearchQuery(raw: String?): String? {
    if (raw.isNullOrBlank()) return null
    var text: String = raw
    SEASON_MARKERS.forEach { text = it.replace(text, " ") }
    return text.replace(WHITESPACE, " ").trim().takeIf { it.isNotBlank() }
}

private val WHITESPACE = Regex("""\s+""")

private val SEASON_MARKERS = listOf(
    Regex.cached("""\b\d+(st|nd|rd|th)\s+season\b""", RegexOption.IGNORE_CASE),
    Regex.cached("""\bseason\s*\d+\b""", RegexOption.IGNORE_CASE),
    Regex.cached("""\bpart\s*\d+\b""", RegexOption.IGNORE_CASE),
    Regex.cached("""\bcour\s*\d+\b""", RegexOption.IGNORE_CASE),
    Regex.cached("""\bfinal\s+season\b""", RegexOption.IGNORE_CASE),
    Regex.cached("""\s+(ii|iii|iv|v|vi|vii|viii|ix|x)\s*$""", RegexOption.IGNORE_CASE),
)

/**
 * Whether a TMDB record is plausibly the same show as an AniList one.
 *
 * Deliberately strict about the thing that goes wrong. A mismatched pairing does not show up as a
 * missing thumbnail, which a viewer can shrug at, but as another show's episodes illustrating this
 * one — the same failure the Konoha lookup already refuses to risk on adult titles, and exactly
 * what the bundled map offers for Dandadan.
 */
internal fun titlesMatch(media: Media, candidate: TmdbSeries): Boolean {
    val ours = listOf(media.title.romaji, media.title.english, media.title.native)
        .map(::normalizeTitle)
        .filter { it.length >= MIN_TITLE_LENGTH }
    val theirs = listOf(candidate.name, candidate.original_name)
        .map(::normalizeTitle)
        .filter { it.length >= MIN_TITLE_LENGTH }
    if (ours.isEmpty() || theirs.isEmpty()) return false
    return ours.any { mine ->
        theirs.any { other -> mine == other || mine.contains(other) || other.contains(mine) }
    }
}

/** Below this a containment test stops meaning anything — "one" is inside a great many titles. */
private const val MIN_TITLE_LENGTH = 6

/** How far a TMDB season's first-episode year may sit from AniList's and still be that season. */
private const val SEASON_YEAR_SLACK = 1

/**
 * How far a run's opening episode may sit from AniList's start date and still be that season's
 * first. Wide enough for a premiere screened early or held back a fortnight, and nowhere near the
 * months that separate one season from the next.
 */
private const val SEASON_OPENER_TOLERANCE_DAYS = 21L

/**
 * The season of a TMDB series that holds the AniList season being shown, or null when none does
 * and the series must be split by an episode group instead.
 *
 * An exact episode count is the strongest signal available and the day the run opened is the
 * tie-break, since a series can repeat a count across seasons. Specials (season 0) are never it.
 */
internal fun pickSeason(
    seasons: List<TmdbSeasonSummary>,
    wantedEpisodes: Int?,
    wantedYear: Int?,
    wantedStart: String? = null,
): TmdbSeasonSummary? {
    val real = seasons.filter { it.season_number > 0 && it.episode_count > 0 }
    if (real.isEmpty()) return null
    if (wantedEpisodes != null) {
        // A known count is binding, and a season of the wrong length is refused even when its year
        // is the only one that fits. TMDB holds Dandadan's two seasons as one season of 24 aired in
        // 2024; matching that on the year alone would have handed AniList's twelve-episode first
        // season a twenty-four episode run and put the wrong still on every row of the second.
        val sameCount = real.filter { it.episode_count == wantedEpisodes }
        // Two cours of one series are the same length in the same year, so the year below cannot
        // separate them and takes whichever TMDB listed first — see [nearestOpener].
        nearestOpener(sameCount, wantedStart) { it.air_date }?.let { return it }
        sameCount.firstOrNull { yearOf(it.air_date) == wantedYear }?.let { return it }
        // A single season of the right length and nothing else claiming that length is still the
        // answer; a year that disagrees by one is a season that started in December or slipped.
        // Years apart is a different broadcast season that happens to be the same length, and that
        // is decided by [farYearSeason] after the episode groups have had their turn.
        return sameCount.singleOrNull()?.takeIf { yearIsNear(it.air_date, wantedYear) }
    }
    if (wantedYear != null) {
        val sameYear = real.filter { yearOf(it.air_date) == wantedYear }
        if (sameYear.size == 1) return sameYear.first()
    }
    // A series with exactly one season and no count to go on is unambiguous by construction.
    return real.singleOrNull()
}

/**
 * The lone count match [pickSeason] held back because its year is nowhere near the entry's.
 *
 * Attack on Titan is why this exists. AniList's Final Season Part 2 is twelve episodes from 2022;
 * TMDB keeps the Final Season as one season of 28, and its *second* season is twelve episodes from
 * 2017. Twelve was unique, so the count rule took it and Part 2 was decorated with 2017's titles
 * and stills. Five years apart is not a season TMDB dated differently, so it is asked last: the
 * episode groups answer first, and one of them holds a "Final Season Part 2" of exactly twelve
 * beginning in 2022.
 *
 * Still returned when nothing else matches, because a count match with an implausible year beats no
 * episode titles at all — that is what this used to return outright.
 */
internal fun farYearSeason(
    seasons: List<TmdbSeasonSummary>,
    wantedEpisodes: Int?,
    wantedYear: Int?,
): TmdbSeasonSummary? {
    if (wantedEpisodes == null) return null
    return seasons
        .filter { it.season_number > 0 && it.episode_count == wantedEpisodes }
        .singleOrNull()
        ?.takeUnless { yearIsNear(it.air_date, wantedYear) }
}

/**
 * Whether a TMDB season's year is close enough to be the same broadcast season.
 *
 * One year of slack, because the two catalogues are not measuring the same thing: TMDB dates a
 * season by its first episode while AniList files a show by the season it is announced for, so an
 * autumn run crossing into January is routinely a year apart. Nothing to compare is not evidence
 * against a match, so both missing values pass.
 */
private fun yearIsNear(airDate: String?, wantedYear: Int?): Boolean {
    if (wantedYear == null) return true
    val year = yearOf(airDate) ?: return true
    return abs(year - wantedYear) <= SEASON_YEAR_SLACK
}

/**
 * Every numbered TMDB season, in order, when together they are exactly the AniList entry.
 *
 * Naruto Shippuden is one AniList entry of 500 episodes and twenty TMDB seasons that add up to
 * exactly 500. No season is that long, so the matching fell through to the episode groups, and the
 * any-length opener rule in [pickGroup] took the 32-episode first arc of a community "Released
 * Order" grouping — whose editor had filed episode 11 fifth. Episodes 1-32 were relabelled from
 * that, and everything after 32 had no catalogue at all.
 *
 * A count that is the sum of every season is the whole series, so the seasons are concatenated.
 * Empty when there is only one season (nothing to join) or the sum is anything else.
 */
internal fun wholeSeriesSeasons(seasons: List<TmdbSeasonSummary>, wantedEpisodes: Int?): List<TmdbSeasonSummary> {
    if (wantedEpisodes == null) return emptyList()
    val numbered = seasons
        .filter { it.season_number > 0 && it.episode_count > 0 }
        .sortedBy { it.season_number }
    if (numbered.size < 2 || numbered.sumOf { it.episode_count } != wantedEpisodes) return emptyList()
    return numbered
}

/**
 * Whether a group run lists its episodes in TMDB's own broadcast numbering.
 *
 * Episode groups are hand-edited, and nothing stops an editor filing episodes out of order: the
 * "Released Order" grouping of Naruto Shippuden puts episode 11 fifth in its first arc. The app
 * numbers a run by position (see [toMetadata]), so a shuffled run puts one episode's title and still
 * on another. A run that is a season's broadcast split — the only kind worth taking — counts up.
 */
internal fun isBroadcastOrder(episodes: List<TmdbEpisode>): Boolean =
    // A run without TMDB's numbering cannot be judged, and is not refused for it.
    episodes.any { it.episode_number <= 0 } || episodes.zipWithNext().all { (previous, next) ->
        previous.season_number < next.season_number ||
            (previous.season_number == next.season_number && previous.episode_number < next.episode_number)
    }

/**
 * The run of a "Seasons" episode group that holds the AniList season being shown.
 *
 * Unlike the seasons above, these runs *are* the broadcast split, so a run beginning on the day the
 * AniList season began is that season however long TMDB made it. Bungou Stray Dogs is why that last
 * rule exists: its whole 60-episode run is one TMDB season, and the group that splits it back into
 * cours gives the second cour thirteen episodes — its twelve, plus the OVA AniList files as a
 * separate entry. Thirteen is not twelve, so the count rule refused it and the year then handed the
 * 2016 autumn season the 2016 spring one's twelve episodes: every row of season two carried season
 * one's title and still. An extra episode on the end of the right run costs nothing, because
 * `alignMetadataToSeason` cuts a run longer than the season back to it by air date.
 */
internal fun pickGroup(
    groups: List<TmdbGroup>,
    wantedEpisodes: Int?,
    wantedYear: Int?,
    wantedStart: String? = null,
): TmdbGroup? {
    // A group's specials run is never a season, and it opens beside one: The Apothecary Diaries'
    // starts the day after season one, near enough for the any-length opener rule below to take it.
    val real = groups.filter { it.episodes.isNotEmpty() && !isSpecialsRun(it.name) && isBroadcastOrder(it.episodes) }
    if (real.isEmpty()) return null
    if (wantedEpisodes != null) {
        val sameCount = real.filter { it.episodes.size == wantedEpisodes }
        // The right length and the right day; then the right day at any length, which beats the
        // year below because these runs are the broadcast split and a run starting within a
        // fortnight of the entry *is* that broadcast, while a same-year run is the other cour.
        val opener = nearestOpener(sameCount, wantedStart, TmdbGroup::firstAirDate)
            ?: nearestOpener(real, wantedStart, TmdbGroup::firstAirDate)
        opener?.let { return it }
        sameCount.firstOrNull { yearOf(it.firstAirDate()) == wantedYear }?.let { return it }
        return sameCount.singleOrNull()
    }
    if (wantedYear != null) {
        val sameYear = real.filter { yearOf(it.firstAirDate()) == wantedYear }
        if (sameYear.size == 1) return sameYear.first()
    }
    return nearestOpener(real, wantedStart, TmdbGroup::firstAirDate)
}

/**
 * The specials in [episodes] that belong to [media]: those whose name, up to its first colon, is
 * one of [media]'s titles. Exact after normalising, so "Youjo Shenki" does not take "Youjo Shenki
 * 2"'s episodes, and only a run exactly as long as AniList says the entry is counts.
 */
internal fun specialsRunFor(media: Media, episodes: List<TmdbEpisode>): List<TmdbEpisode> {
    val wanted = media.episodes ?: return emptyList()
    val titles = listOf(media.title.romaji, media.title.english)
        .map { it?.let(::normalizeRunTitle).orEmpty() }
        .filter { it.length >= MIN_TITLE_LENGTH }
        .toSet()
    if (titles.isEmpty()) return emptyList()
    val run = episodes.filter { episode ->
        val name = episode.name ?: return@filter false
        ':' in name && normalizeRunTitle(name.substringBefore(':')) in titles
    }
    return if (run.size == wanted) run else emptyList()
}

/** Unlike [normalizeTitle] this keeps season markers: they are what tells two spin-off runs apart. */
private fun normalizeRunTitle(raw: String): String = raw.lowercase().filter { it.isLetterOrDigit() }

private fun isSpecialsRun(name: String?): Boolean =
    name?.trim()?.lowercase()?.startsWith("special") == true

/**
 * The candidate whose first episode aired nearest [wantedStart], or null when none is near enough
 * and when two are equally near.
 *
 * A year says which *broadcast* year a run belongs to, and a two-cour series has two runs in one
 * year — so the year cannot separate them and whichever TMDB listed first won. That is how Space
 * Dandy 2 (thirteen episodes, July 2014) was given season one's thirteen episodes of January 2014,
 * and Bungou Stray Dogs 2nd Season season one's.
 *
 * The day can separate them, because TMDB dates a cour to the day and AniList's start date is the
 * same broadcast. Nearest rather than equal: the two catalogues disagree by a day whenever one
 * recorded a broadcast date and the other a streaming one — Space Dandy's own first season is 5
 * January on AniList and 4 January on TMDB — and demanding equality would throw the match away over
 * it. A tie is left undecided rather than guessed; the rules after this one can still answer.
 */
private fun <T> nearestOpener(candidates: List<T>, wantedStart: String?, firstAir: (T) -> String?): T? {
    if (wantedStart.isNullOrBlank()) return null
    val scored = candidates
        .mapNotNull { candidate -> daysApart(firstAir(candidate), wantedStart)?.let { it to candidate } }
        .filter { (distance, _) -> distance <= SEASON_OPENER_TOLERANCE_DAYS }
    if (scored.isEmpty()) return null
    val best = scored.minOf { (distance, _) -> distance }
    return scored.filter { (distance, _) -> distance == best }.singleOrNull()?.second
}

/** Days between two `YYYY-MM-DD` dates, or null unless both parse as whole dates. */
private fun daysApart(date: String?, other: String?): Long? {
    val left = parseDay(date) ?: return null
    val right = parseDay(other) ?: return null
    return abs(ChronoUnit.DAYS.between(left, right))
}

private fun parseDay(date: String?): LocalDate? =
    date?.takeIf { it.length >= 10 }?.let { runCatching { LocalDate.parse(it.substring(0, 10)) }.getOrNull() }

private fun TmdbGroup.firstAirDate(): String? = episodes.firstOrNull()?.air_date

private fun yearOf(date: String?): Int? = date?.take(4)?.toIntOrNull()

/** An AniList start date as the `YYYY-MM-DD` TMDB writes, or null unless all three parts are known. */
internal fun isoAirDate(start: FuzzyDate?): String? {
    val year = start?.year ?: return null
    val month = start.month ?: return null
    val day = start.day ?: return null
    return "%04d-%02d-%02d".format(year, month, day)
}

/**
 * The films that are [media]'s episodes, in episode order, or null unless they account for it
 * exactly.
 *
 * Three things must all hold, because the failure being guarded against is another title's
 * artwork on this one. Each film's title must contain the entry's own name once "OVA"/"Movie"
 * and the like are taken off it — TMDB titles an OVA film "<series> <subtitle>". Each must be
 * released within the entry's own run, from its start date to its end date, with the same slack a
 * season opener gets: that is what separates Re:ZERO's two OVAs from the 2016 compilation film
 * TMDB files under the bare series name. And the count must equal the entry's episode count; a
 * surplus or a shortfall means the films are not this entry, or not all of it.
 */
internal fun pickMovieRun(media: Media, movies: List<TmdbMovie>): List<TmdbMovie>? {
    val wanted = media.episodes ?: return null
    val start = parseDay(isoAirDate(media.startDate)) ?: return null
    val end = parseDay(isoAirDate(media.endDate)) ?: start
    val bases = listOf(media.title.romaji, media.title.english, media.title.native)
        .map { normalizeTitle(stripFormatMarkers(it)) }
        .filter { it.length >= MIN_TITLE_LENGTH }
        .distinct()
    if (bases.isEmpty()) return null
    val run = movies
        .distinctBy { it.id }
        .filter { movie ->
            val released = parseDay(movie.release_date) ?: return@filter false
            val inRun = !released.isBefore(start.minusDays(SEASON_OPENER_TOLERANCE_DAYS)) &&
                !released.isAfter(end.plusDays(SEASON_OPENER_TOLERANCE_DAYS))
            val theirs = listOf(movie.title, movie.original_title)
                .map(::normalizeTitle)
                .filter { it.isNotEmpty() }
            inRun && theirs.any { title -> bases.any { base -> title.contains(base) } }
        }
        .sortedBy { it.release_date }
    return run.takeIf { it.size == wanted }
}

/** What to search TMDB's films for: each title as written, and without its format word. */
internal fun movieSearchQueries(media: Media): List<String> =
    listOf(media.title.english, media.title.romaji)
        .flatMap { listOf(it?.trim(), stripFormatMarkers(it)) }
        .filterNot { it.isNullOrBlank() }
        .filterNotNull()
        .distinct()

/**
 * A film's title as an episode title: the part after the series name, so the card reads
 * "Memory Snow" rather than repeating the name the page already carries in its header.
 */
internal fun movieEpisodeTitle(media: Media, movie: TmdbMovie): String? {
    val title = movie.title?.trim()?.takeIf { it.isNotBlank() } ?: return null
    val prefix = listOf(media.title.english, media.title.romaji)
        .mapNotNull(::stripFormatMarkers)
        .filter { it.length >= MIN_TITLE_LENGTH }
        .firstOrNull { title.startsWith(it, ignoreCase = true) }
        ?: return title
    return title.substring(prefix.length).trim(' ', '-', ':', '–', '—', '~').ifBlank { title }
}

/** A title without the words that say what kind of release it is rather than what it is called. */
internal fun stripFormatMarkers(raw: String?): String? {
    if (raw.isNullOrBlank()) return null
    return FORMAT_MARKERS.replace(raw, " ").replace(WHITESPACE, " ").trim().takeIf { it.isNotBlank() }
}

private val FORMAT_MARKERS = Regex.cached(
    """\b(the\s+movie|movies?|gekijou-?ban|ovas?|oads?|onas?|specials?)\b""",
    RegexOption.IGNORE_CASE,
)
