/** The bundled id-map's claim about which TMDB record an AniList id corresponds to. */
data class TmdbRef(val id: Int, val type: String?)

/**
 * The bundled id-map's placement of an AniList id within a TheTVDB series.
 *
 * [season] is null for an entry TheTVDB files outside the numbered run — a film or an OVA — which
 * is why it does not default to 1: a chain that assumed 1 would collect every special into the
 * first season.
 */
data class TvdbRef(val id: Int, val season: Int?)

